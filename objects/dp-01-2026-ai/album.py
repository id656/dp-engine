def shower_section(sh, X, Y, k=25.0):
    """Разрез 1-1 по оси лейки (x=700), вид на стену В: уклон, стекло, трап, короб инсталляции."""
    ev = EV(X, Y, k)
    from details import R as DR, hatch as DH
    Y0 = 4550

    def S(y):
        return y - Y0
    DR(sh, ev, -200, -300, 0, 3300, 'brick')
    DR(sh, ev, 2200, -300, 2300, 3300, 'brick')
    DR(sh, ev, 0, -300, 2200, -150, 'concrete')
    DR(sh, ev, -200, 3150, 2300, 3300, 'concrete')
    gl0, gl1 = S(5335), S(5350)
    DH(sh, ev, [(0, -150), (2200, -150), (2200, 5), (gl1, 5), (90, -10), (90, -40), (0, -40)], 'screed')
    DH(sh, ev, [(90, -10), (gl1, 5), (gl1, 20), (90, 5)], 'tile')
    DR(sh, ev, gl1, 5, 2000, 20, 'tile')
    DR(sh, ev, 10, -110, 90, -40, 'metal')
    DR(sh, ev, 0, 20, 12, 2420, 'tile')
    # короб инсталляции (разрез): ГКЛВ на каркасе + плитка С4
    bx0 = S(6550)
    DR(sh, ev, bx0, 5, 2200, 2420, 'gkl')
    DR(sh, ev, bx0 - 12, 20, bx0, 2420, 'tile')
    DR(sh, ev, 0, 2420, 2200, 2432, 'gkl')
    sh.line(ev.P(gl0, 20), ev.P(gl0, 2020), lw=0.6, layer='A-DET', color=BLACK)
    sh.line(ev.P(gl1, 20), ev.P(gl1, 2020), lw=0.6, layer='A-DET', color=BLACK)
    # душ (стена Б, по оси разреза)
    R(sh, ev, 12, 1060, 60, 1140, fill=(0.12, 0.12, 0.12), style=LT)
    sh.poly([ev.P(40, 1140), ev.P(40, 2150), ev.P(330, 2150)], closed=False, lw=0.6, layer='A-DET', color=BLACK)
    R(sh, ev, 210, 2130, 450, 2160, fill=(0.12, 0.12, 0.12), style=LT)
    # в виде за плоскостью разреза (стена В): тумба, зеркало, полотенцесушитель, унитаз
    it = {i.get('key'): i for i in D.ITEMS}
    van = it['05-vanity']
    s0, s1 = S(van['axis'] - van['width'] / 2), S(van['axis'] + van['width'] / 2)
    R(sh, ev, s0, van['z'][0], s1, van['z'][1], fill=(0.80, 0.74, 0.66), style=LT)
    mr = it['05-mirror']['rect']; mz = it['05-mirror']['z']
    cx, cz = (S(mr[1]) + S(mr[3])) / 2, (mz[0] + mz[1]) / 2
    from core import ell_pts
    pts = [ev.P(cx + (S(mr[3]) - S(mr[1])) / 2 * math.cos(math.radians(a)), cz + (mz[1] - mz[0]) / 2 * math.sin(math.radians(a)))
           for a in range(0, 360, 10)]
    sh.poly(pts, lw=0.3, layer='A-DET', color=MID, fill=(0.90, 0.93, 0.95))
    tr = it['05-towel']['rect']; tz = it['05-towel']['z']
    R(sh, ev, S(tr[1]), tz[0], S(tr[3]), tz[1], style=LT)
    for zz in range(int(tz[0]) + 100, int(tz[1]), 100):
        Ln(sh, ev, S(tr[1]), zz, S(tr[3]), zz, style=LT)
    wc = it['05-wc']
    wr = item_rect(wc)
    if wr:
        R(sh, ev, S(wr[1]), 0 + 20, S(wr[3]), wc['z'][1], style=LT)
    fv = FV(ev)
    mdim(sh, fv, 'x', [20, 1100, 2020, 2150, 2420, 3150], 2550, ext=2200, h=1.8)
    mdim(sh, fv, 'y', [0, gl1, bx0, 2200], -560, ext=-150, h=1.8)
    sh.text(ev.P(380, 300), 'i ≈ 2 %  →  к трапу', h=1.6, layer='A-TEXT', color=(0.1, 0.35, 0.7), bg=True)
    sh.text(ev.P(1100, 2700), 'плита ≈ +3,150; воздуховод вентилятора над потолком', h=1.5, ha='c', layer='A-TEXT', bg=True)
    for s_, z_, t_ in [(150, 700, 'С7'), (S(5670), 300, 'С3'), (S(5670), 1950, 'С11'), (S(6255), 1750, 'С10'),
                       (S(6200) + 60, 520, 'С1'), (gl1 + 120, 2100, 'С9'), (60, -260, 'С8')]:
        bubble(sh, ev.P(s_, z_), t_, r=2.0, h=1.4)
    section_title(sh, X - 8, Y + 3500 / k, 'Разрез 1-1 по душевой зоне (вид на стену В)', f'М 1:{int(k)}', h=2.4)


