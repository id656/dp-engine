def _w(room, lab, k):
    """Ширина поля развёртки на листе (как в elev._elev_size): поле слева, стена, размеры справа."""
    L = wall_geom(room, lab)['L']
    title_w = 6.0 + tw(f'Развёртка {D.wall_span(room, lab)}  М 1:{int(k)}', 2.6, 'BoldObl') + 4
    return max(120 / k + L / k + 330 / k + 9, title_w)


def row(sh, room, labs, k, top, x0=25.0, levels_last=True, gap=0.0):
    """Ряд развёрток слева направо; top — верх заголовков (мм листа). Возвращает правый край и низ ряда."""
    zf = D.ROOM[room]['level'] or 0
    zc = D.ROOM[room]['ceil']
    Y0 = top - (zc + 330) / k - 3.5
    x = x0
    for i, lab in enumerate(labs):
        last = i == len(labs) - 1
        elevation(sh, room, lab, x + 120 / k + 2, Y0, k, levels='right' if (last and levels_last) else None, vdim_off=330)
        x += _w(room, lab, k) + gap
    right = x + (31 if levels_last else 0)
    bottom = Y0 + (zf - 620) / k - 3.0
    return right, bottom


def codes_of(room, extra=()):
    out = []
    dflt = D.WALL_DEFAULT.get(room)
    if dflt:
        out.append(dflt)
    for (r, lab, s0, s1, z0, z1, code) in D.WALL_ZONES:
        if r == room and code != 'X' and code not in out:
            out.append(code)
    for c in extra:
        if c not in out:
            out.append(c)
    return out


def tile_table(sh, room, x, y, codes):
    import tables as TB
    q = TB.tile_quantities()
    rows = []
    for c in codes:
        if (room, c) in q:
            res = 0.15 if D.MATERIALS.get(c, {}).get('tex') == 'herringbone' else 0.10
            rows.append([c, D.FINISH[c].split(',')[0], num(q[(room, c)], 2), f'+{int(res * 100)} %',
                         num(q[(room, c)] * (1 + res), 2)])
    return table(sh, x, y, [10, 78, 18, 13, 20], ['Код', 'Материал', 'Нетто, м²', 'Запас', 'К заказу, м²'], rows,
                 aligns=['c', 'l', 'r', 'c', 'r'], title=f'Плитка помещения {room}', title_h=2.3, row_h=4.6, h=1.7)


