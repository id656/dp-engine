def sheets():
    """Порядок по заданию бюро: титул, общие данные, дизайн-проект, указания; планы на всю квартиру
    (ведомость отделки — после потолков); спецификации; листы помещений; узлы; визуализации (панорамы 360°)."""
    import assemble as AS
    import plans as PL
    import tables as TB
    common = {k: (k, n, fn) for k, n, fn in AS.common_sheets()}
    common['dsc'] = ('dsc', 'Ведомость дверей (эскизы типов)', PL.sheet_door_schedule)
    order = ['01', '02', '03', '04', 'obm', 'dem', 'mnt', 'fur', 'flr', 'hft', 'cei', 'fin', 'lgt', 'swi', 'out', 'plb',
             'dor', 'dsc', 'ven', 'mat', 'ssp', 'lsp', 'eui']
